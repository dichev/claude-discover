import vocab from './vocab.json' with { type: 'json' } // generated by test/scripts/tokenizer-vocab.mjs

// Offline Claude token counts, a simplified port of ctok (https://github.com/sanderland/ctok): the text is rewritten with word-boundary
// and case markers, then covered with the fewest pieces of the vocabulary. No message framing, none of ctok's rules for rare scripts.

const BOW = '\uFDD0', EOW = '\uFDD1', SHIFT = '\uFDD3' // begin/end of word, Capitalized: one codepoint each, as the vocabulary spells them
const SEAM = new RegExp(`${EOW} (${SHIFT}?)${BOW}`, 'g') // the single space between two marked runs is the boundary itself, not a character
const CONTRACTIONS = new Set(['s', 't', 'd', 'm', 'll', 're', 've'])

// Ideographs and astral characters (emoji) stand alone: no word model, no markers, and neither does CJK punctuation
const IDEOGRAPHS = String.raw`\u3005\u3006\u3031-\u3035\u303B\u303C\u3400-\u4DBF\u4E00-\u9FFF\uAC00-\uD7A3\uF900-\uFAFF\u{10000}-\u{10FFFF}`
const PUNCT      = String.raw`[[\p{P}\p{S}\p{Cf}\p{Cn}\p{No}\p{Nd}[\p{M}--\p{Alphabetic}]]--[0-9\u3001-\u303F\uFE00-\uFE0F\u{10000}-\u{10FFFF}]]`

// Maximal runs of one character class: a word gets both boundary markers, a punct run one on each side that touches a space,
// the rest (digits, ideographs, emoji) none
const RUNS = new RegExp([
  String.raw`(?<space>[\t\n\p{Z}]+)`,
  String.raw`(?<word>[[\p{L}[\p{M}&&\p{Alphabetic}]]--[${IDEOGRAPHS}]]+)`,
  String.raw`(?<punct>${PUNCT}[${PUNCT}\uFE00-\uFE0F]*)`, // a variation selector rides the symbol before it
  String.raw`(?<other>[^])`,
].join('|'), 'gv')

// What the API does to the text before tokenizing it
const normalize = text => text
  .replace(/(?<=<)(\/?)\/?antml:(?:\/?antml:)*(?=[^<>])/gi, '$1') // the reserved tag namespace is dropped
  .normalize('NFC')
  .replace(/[\x01-\x08\x0B-\x1F\x7F-\x9F\uE000-\uF8FF]/g, '') // controls (CR included) and private-use characters cost nothing
  .replace(/[\0\u00A0\u1680\u2000-\u200A\u2028\u2029\u202F\u205F]/g, ' ')
  .replace(/(?<!\n)\n+$/, '') // final newlines merge into the token of whatever follows the text; the lookbehind keeps a long run mid-text linear

const isUpper = c => c !== c.toLowerCase() && !'İẞ'.includes(c) // these two measure as caseless

// A Capitalized word is spelled as a marker plus its lowercase form; any other mix of cases stays literal
const markCase = word => {
  const [head, ...tail] = word
  return isUpper(head) && !tail.some(isUpper) ? SHIFT + BOW + head.toLowerCase() + tail.join('') : BOW + word
}

// Text → the marked stream the vocabulary's pieces are spelled in
const stream = text => {
  const runs = Array.from(text.matchAll(RUNS), m => m.groups) // each run's text, under its class name
  const spaceBefore = i => runs[i - 1]?.space?.endsWith(' ')
  const spaceAfter  = i => /^ (?! )/.test(runs[i + 1]?.space ?? '') // a single space only, never a run of them
  const opensWord   = i => runs[i].punct === "'" && runs[i + 1]?.word // 'quoted: the apostrophe takes no boundary of its own
  const contraction = i => CONTRACTIONS.has(runs[i].word) && runs[i - 1]?.punct === "'" // it's: the apostrophe is the suffix's opening boundary

  const marked = runs.map(({ space, word, punct, other }, i) => {
    if (word) return (contraction(i) ? word : markCase(word)) + EOW
    if (punct) return (spaceBefore(i) && !opensWord(i) ? BOW : '') + punct + (spaceAfter(i) ? EOW : '')
    return space ?? other
  })
  return marked.join('').replace(SEAM, `${EOW}$1${BOW}`)
}

// The pieces as a trie of codepoints
const buildTrie = pieces => {
  const root = new Map()
  for (const piece of pieces) {
    let node = root
    for (const c of piece) {
      if (!node.has(c)) node.set(c, new Map())
      node = node.get(c)
    }
    node.end = true
  }
  return root
}

// The vocabulary's lookup tables, and the texts counted so far: the view re-renders on every transcript append, re-counting the same prompts and tools
let trie // built on the first count, 10ms a process that never counts doesn't pay as it starts
const prefixes = new Set(vocab.bytePrefixes)
const counts   = new Map()

// A character no piece covers costs its longest known UTF-8 prefix as one token, then one per remaining byte.
// Memoized: most ideographs and every emoji have no piece, so a text in them pays this per character
const encoder  = new TextEncoder()
const floors   = new Map()
const byteCost = c => {
  if (!floors.has(c)) {
    const hex   = Array.from(encoder.encode(c), b => b.toString(16).padStart(2, '0'))
    const known = hex.findLastIndex((_, i) => prefixes.has(hex.slice(0, i).join('')))
    floors.set(c, 1 + hex.length - Math.max(known, 1))
  }
  return floors.get(c)
}

// The fewest pieces that cover the text's marked stream
const cover = text => {
  trie ??= buildTrie(vocab.pieces)
  const chars = Array.from(stream(normalize(text)))
  const best  = new Float64Array(chars.length + 1).fill(Infinity) // best[i]: the fewest tokens covering the first i characters
  best[0] = 0
  for (let start = 0; start < chars.length; start++) {
    const c = chars[start]
    if (!trie.get(c)?.end) best[start + 1] = Math.min(best[start + 1], best[start] + byteCost(c)) // a piece of its own always costs less
    let node = trie
    for (let end = start; end < chars.length && (node = node.get(chars[end])); end++) {
      if (node.end) best[end + 1] = Math.min(best[end + 1], best[start] + 1)
    }
  }
  return best[chars.length]
}

// The estimated number of tokens `text` takes, as Opus 4.7 and every model since tokenize it:
// an older model, on another tokenizer, took 20-45% fewer for English and code
export const countTokens = text => {
  if (!text) return 0
  if (!counts.has(text)) {
    if (counts.size >= 10000) counts.delete(counts.keys().next().value)
    counts.set(text, cover(text))
  }
  return counts.get(text)
}
